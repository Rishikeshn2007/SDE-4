from dataclasses import dataclass, field


@dataclass
class SourceReference:
    """Reference to the origin of a piece of context.

    Attributes:
        source_id (str): Non-empty source identifier; no physical unit.
        source_type (str): Non-empty source category; no physical unit.
        description (str): Optional description; defaults to an empty string.
    """

    source_id: str
    source_type: str
    description: str = ""

    def validate(self):
        """Validate the source reference."""
        if not isinstance(self.source_id, str) or not self.source_id.strip():
            raise ValueError("source_id must be a non-empty string")

        if not isinstance(self.source_type, str) or not self.source_type.strip():
            raise ValueError("source_type must be a non-empty string")

        if not isinstance(self.description, str):
            raise ValueError("description must be a string")


@dataclass
class ContextItem:
    """A single piece of information used for reasoning.

    Attributes:
        item_id (str): Non-empty item identifier; no physical unit.
        content (str): Non-empty text containing contextual information.
        source (SourceReference): Valid reference to the information source.
    """

    item_id: str
    content: str
    source: SourceReference

    def validate(self):
        """Validate the context item."""
        if not isinstance(self.item_id, str) or not self.item_id.strip():
            raise ValueError("item_id must be a non-empty string")

        if not isinstance(self.content, str) or not self.content.strip():
            raise ValueError("content must be a non-empty string")

        if not isinstance(self.source, SourceReference):
            raise ValueError("source must be a SourceReference object")

        self.source.validate()


@dataclass
class ScreenContext:
    """Container for context items used by the reasoning system.

    Attributes:
        context_id (str): Non-empty context identifier; no physical unit.
        items (list[ContextItem]): List of valid context items; defaults to empty.
        capture_enabled (bool): Must be False to protect privacy.
    """

    context_id: str
    items: list[ContextItem] = field(default_factory=list)
    capture_enabled: bool = False

    def validate(self):
        """Validate the screen context."""
        if not isinstance(self.context_id, str) or not self.context_id.strip():
            raise ValueError("context_id must be a non-empty string")

        if not isinstance(self.items, list):
            raise ValueError("items must be a list")

        if not isinstance(self.capture_enabled, bool):
            raise ValueError("capture_enabled must be boolean")

        if self.capture_enabled:
            raise ValueError(
                "Screen capture must remain disabled in this project"
            )

        for item in self.items:
            if not isinstance(item, ContextItem):
                raise ValueError("Each item must be a ContextItem object")

            item.validate()


@dataclass
class ReasoningRequest:
    """Represents a request for the reasoning system.

    Attributes:
        request_id (str): Non-empty request identifier; no physical unit.
        question (str): Non-empty question to answer.
        context (ScreenContext): Valid context available for the answer.
    """

    request_id: str
    question: str
    context: ScreenContext

    def validate(self):
        """Validate the reasoning request."""
        if not isinstance(self.request_id, str) or not self.request_id.strip():
            raise ValueError("request_id must be a non-empty string")

        if not isinstance(self.question, str) or not self.question.strip():
            raise ValueError("question must be a non-empty string")

        if not isinstance(self.context, ScreenContext):
            raise ValueError("context must be a ScreenContext object")

        self.context.validate()


@dataclass
class ReasoningResult:
    """Represents the result produced by the reasoning system.

    Attributes:
        request_id (str): Non-empty identifier of the original request.
        answer (str): Non-empty answer generated by the reasoning system.
        source_ids (list[str]): List of non-empty source identifiers.
        status (str): Must be either 'success' or 'error'.
    """

    request_id: str
    answer: str
    source_ids: list[str] = field(default_factory=list)
    status: str = "success"

    def validate(self):
        """Validate the reasoning result."""
        if not isinstance(self.request_id, str) or not self.request_id.strip():
            raise ValueError("request_id must be a non-empty string")

        if not isinstance(self.answer, str) or not self.answer.strip():
            raise ValueError("answer must be a non-empty string")

        if not isinstance(self.source_ids, list):
            raise ValueError("source_ids must be a list")

        if not isinstance(self.status, str) or self.status not in {
            "success",
            "error",
        }:
            raise ValueError("status must be 'success' or 'error'")

        for source_id in self.source_ids:
            if not isinstance(source_id, str) or not source_id.strip():
                raise ValueError("Each source ID must be a non-empty string")